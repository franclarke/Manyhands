#!/usr/bin/env node
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { readJournal, summarizeRunJournal, toCsv } from "./lib/study-metrics.mjs";

const RUN_COLUMNS = [
  "runId", "series", "increment", "taskId", "condition", "repetition", "journalPath",
  "delivered", "lifecycle", "wallClockSeconds", "attempts", "repairs", "tokensTotal",
  "usageStatus", "usageReportedAttempts", "usageUnavailableAttempts", "externalOracleCoverage",
  "policyVersion", "candidateTreeHash", "leafCount", "graphDepth", "branchingFactor"
];
const ASSESSMENT_COLUMNS = [
  "runId", "series", "increment", "taskId", "condition", "repetition", "policyVersion",
  "candidateTreeHash", "unitKey", "nodeId", "selected", "leafFeasible", "splitViable",
  "benefit", "cost", "splitAdvantage", "minimumAdvantage", "evidenceRefs", "rationale",
  "contextRelief", "parallelism", "faultIsolation", "coordination", "pathOverlap",
  "validationDuplication", "uncertainty"
];

const runsRoot = resolve(argOf("--runs") ?? "docs/tesis/evidence/warehouse/final");
const outDir = resolve(argOf("--out") ?? "docs/tesis/evidence/warehouse/final/results");
await mkdir(outDir, { recursive: true });

const journals = await findJournals(runsRoot);
const runs = [];
const assessments = [];
for (const journalPath of journals) {
  const events = await readJournal(journalPath);
  const metadata = await readFirstJson(dirname(journalPath), ["cell.json", "run.json", "manifest.json"]);
  const oracle = normalizeOracle(await readFirstJson(dirname(journalPath), ["oracle-result.json", "oracle.json"]));
  const summary = summarizeRunJournal(events, oracle);
  const identity = {
    series: metadata?.series ?? inferredSeries(journalPath),
    increment: metadata?.increment ?? metadata?.incrementId ?? "unavailable",
    taskId: metadata?.taskId ?? "unavailable",
    condition: metadata?.condition ?? summary.condition,
    repetition: metadata?.repetition ?? "unavailable"
  };
  runs.push({
    ...identity,
    ...summary,
    journalPath: relative(runsRoot, journalPath).replaceAll("\\", "/")
  });
  assessments.push(...summary.strategyAssessments.map((assessment) => ({
    ...identity,
    ...assessment,
    evidenceRefs: assessment.evidenceRefs,
    ...assessment.features
  })));
}
runs.sort(compareRows);
assessments.sort(compareRows);

await writeFile(join(outDir, "runs.csv"), toCsv(runs, RUN_COLUMNS), "utf8");
await writeFile(join(outDir, "strategy-assessments.csv"), toCsv(assessments, ASSESSMENT_COLUMNS), "utf8");
await writeFile(join(outDir, "longitudinal-results.md"), markdownFor(runs.filter((run) => run.series === "longitudinal"), "Longitudinal"), "utf8");
await writeFile(join(outDir, "comparison-results.md"), markdownFor(runs.filter((run) => run.series === "comparison"), "Comparación A/B/C"), "utf8");
await writeFile(join(outDir, "wall-clock.svg"), figureFor(runs), "utf8");
process.stdout.write(`derived ${runs.length} runs and ${assessments.length} assessments\n`);

async function findJournals(root) {
  const output = [];
  const visit = async (directory) => {
    let entries;
    try {
      entries = await readdir(directory, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const target = join(directory, entry.name);
      if (entry.isDirectory()) await visit(target);
      else if (entry.name === "run.events.v2.jsonl" || entry.name.endsWith(".events.jsonl")) output.push(target);
    }
  };
  await visit(root);
  return output.sort();
}

async function readFirstJson(directory, names) {
  for (const name of names) {
    try {
      return JSON.parse(await readFile(join(directory, name), "utf8"));
    } catch {
      // Optional sidecar. Continue to the next declared filename.
    }
  }
  return undefined;
}

function normalizeOracle(value) {
  if (value === undefined) return undefined;
  const total = value.total ?? value.criteriaTotal ?? value.checks?.length;
  const satisfied = value.satisfied ?? value.criteriaSatisfied ?? value.checks?.filter((check) => check.passed === true).length;
  return Number.isFinite(total) && Number.isFinite(satisfied) ? { total, satisfied } : undefined;
}

function inferredSeries(journalPath) {
  const normalized = journalPath.replaceAll("\\", "/");
  if (normalized.includes("/longitudinal/")) return "longitudinal";
  if (normalized.includes("/comparison/")) return "comparison";
  return "unavailable";
}

function markdownFor(rows, title) {
  const lines = [
    "<!-- GENERATED by derive-warehouse-metrics.mjs. Do not edit by hand. -->",
    `# ${title}`,
    "",
    `Runs analizados: **${rows.length}**. Los fallos permanecen en la tabla y conservan costo medido.`,
    "",
    "| Run | Incremento/tarea | Condición | Entregado | Tiempo (s) | Tokens | Oráculo externo | Hojas |",
    "|---|---|---|---:|---:|---:|---:|---:|"
  ];
  for (const row of rows) {
    lines.push(`| ${row.runId} | ${row.increment !== "unavailable" ? row.increment : row.taskId} | ${row.condition} | ${row.delivered} | ${row.wallClockSeconds} | ${row.tokensTotal} | ${row.externalOracleCoverage} | ${row.leafCount} |`);
  }
  return `${lines.join("\n")}\n`;
}

function figureFor(rows) {
  const width = 900;
  const height = Math.max(140, 60 + rows.length * 28);
  const numeric = rows.map((row) => typeof row.wallClockSeconds === "number" ? row.wallClockSeconds : 0);
  const max = Math.max(1, ...numeric);
  const parts = [`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" font-family="sans-serif" font-size="12">`, `<text x="20" y="24" font-size="15">Wall-clock por run, sin excluir fallos</text>`];
  rows.forEach((row, index) => {
    const y = 50 + index * 28;
    const value = numeric[index];
    const length = Math.round((value / max) * 620);
    parts.push(`<text x="20" y="${y + 10}">${escapeXml(row.runId)}</text>`);
    parts.push(`<rect x="220" y="${y}" width="${length}" height="14" fill="${row.delivered === 1 ? "#1a7f37" : "#b42318"}"/>`);
    parts.push(`<text x="${230 + length}" y="${y + 11}">${escapeXml(String(row.wallClockSeconds))} s</text>`);
  });
  parts.push("</svg>");
  return `${parts.join("\n")}\n`;
}

function compareRows(left, right) {
  return [left.series, left.increment, left.taskId, left.condition, left.repetition, left.runId]
    .join("|").localeCompare([right.series, right.increment, right.taskId, right.condition, right.repetition, right.runId].join("|"));
}

function escapeXml(value) {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

function argOf(flag) {
  const index = process.argv.indexOf(flag);
  return index === -1 ? undefined : process.argv[index + 1];
}
